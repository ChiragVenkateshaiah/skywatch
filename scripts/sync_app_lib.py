"""Copy the shared pure modules from src/lib/ into app/lib/ (docs/CHAT_PLAN.md §3).

The App deploys only app/ (its `source_code_path`), and `bundle deploy` does not upload files
behind a symlink (tested 2026-10-19), so the chat's turn loop and grounding check are copied, not
linked. src/lib/ stays the one place to edit: tests/test_app_lib_sync.py fails when a copy has
drifted. Run after changing any module listed here:

    python scripts/sync_app_lib.py
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHARED = ["chat.py", "grounding.py"]
HEADER = "# GENERATED by scripts/sync_app_lib.py from src/lib/{name} — edit that file, not this one.\n"


def expected(name: str) -> str:
    return HEADER.format(name=name) + (ROOT / "src" / "lib" / name).read_text()


def main() -> None:
    dst = ROOT / "app" / "lib"
    dst.mkdir(exist_ok=True)
    (dst / "__init__.py").write_text(HEADER.format(name="__init__.py"))
    for name in SHARED:
        (dst / name).write_text(expected(name))
        print(f"app/lib/{name} <- src/lib/{name}")


if __name__ == "__main__":
    main()
